a=[1,2,3,4,5,6,7,8,9,"python"]
print(a[0:5])  # Output: [1, 2, 3, 4, 5]
print(a[5:])   # Output: [6, 7, 8, 9, 'python']
print(a[:5])   # Output: [1, 2, 3, 4, 5]
print(a[-5:])  # Output: [5, 6, 7, 8, 9, 'python']
print(a[::2])  # Output: [1, 3, 5, 7, 9]
print(a[1::2]) # Output: [2, 4, 6, 8, 'python']
print(a[::-1]) # Output: ['python', 9, 8, 7, 6, 5, 4, 3, 2, 1]
print(a[2:8:2]) # Output: [3, 5, 7]
